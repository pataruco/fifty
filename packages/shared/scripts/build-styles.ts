// Writes src/generated/assets.ts from the stylesheet, the logo and the
// favicon. Every runtime (the Worker, its tests and plain Node) imports that
// one module, so they all inline the same bytes under the same CSP hash.
//
// Run: node scripts/build-styles.ts
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { transform } from 'esbuild';

export interface AssetSources {
  css: string;
  logoSvg: string;
  faviconSvg: string;
}

const BANNER = '// Generated by scripts/build-styles.ts — do not edit.';

const PATH_DATA = /^[\d\s.,+\-eEMmLlHhVvCcSsQqTtAaZz]+$/;

/**
 * Keeps only the viewBox and each path's d, and marks the logo as
 * decoration: the link around it carries the name.
 */
export function cleanLogo(svg: string): string {
  const viewBox = /<svg\b[^>]*\bviewBox="([\d.\s-]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error('logo: no viewBox');

  const paths = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]*)"/g)].map((m) =>
    (m[1] ?? '').replace(/\s+/g, ' ').trim(),
  );
  if (paths.length === 0) throw new Error('logo: no path');
  for (const d of paths) {
    if (!PATH_DATA.test(d)) throw new Error('logo: unexpected path data');
  }

  return [
    `<svg viewBox="${viewBox.trim()}" aria-hidden="true" focusable="false" fill="currentColor">`,
    ...paths.map((d) => `<path d="${d}"/>`),
    '</svg>',
  ].join('');
}

/** The favicon as a data: link, so the page loads nothing from the network. */
export function faviconDataUrl(svg: string): `data:${string}` {
  if (/@import/i.test(svg)) throw new Error('favicon: @import is not allowed');
  if (/https?:\/\/(?!www\.w3\.org\/2000\/svg")/i.test(svg)) {
    throw new Error('favicon: external links are not allowed');
  }
  const compact = svg.replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();
  return `data:image/svg+xml,${encodeURIComponent(compact)}`;
}

export async function buildAssetsModule(
  sources: AssetSources,
): Promise<string> {
  const { code } = await transform(sources.css, {
    loader: 'css',
    minify: true,
  });
  const css = code.trimEnd();
  const styleHash = `sha256-${createHash('sha256').update(css, 'utf8').digest('base64')}`;
  const literal = (value: string) => JSON.stringify(value);

  return [
    BANNER,
    "import { trustBuildHref } from '../html/href.ts';",
    "import { trustBuildOutput } from '../html/html.ts';",
    '',
    `export const css: string = ${literal(css)};`,
    '',
    `export const styleHash: \`sha256-\${string}\` = ${literal(styleHash)};`,
    '',
    'export const inlineStyle = trustBuildOutput(',
    `  ${literal(`<style>${css}</style>`)},`,
    "  'generated/assets',",
    ');',
    '',
    'export const logoSvg = trustBuildOutput(',
    `  ${literal(cleanLogo(sources.logoSvg))},`,
    "  'generated/assets',",
    ');',
    '',
    'export const faviconHref = trustBuildHref(',
    `  ${literal(faviconDataUrl(sources.faviconSvg))},`,
    "  'generated/assets',",
    ');',
    '',
  ].join('\n');
}

const source = (path: string) => new URL(path, import.meta.url);

if (import.meta.main) {
  const read = (path: string) => readFile(source(path), 'utf8');
  await writeFile(
    source('../src/generated/assets.ts'),
    await buildAssetsModule({
      css: await read('../src/styles/fifty.css'),
      logoSvg: await read('../src/brand/logo.svg'),
      faviconSvg: await read('../src/brand/favicon.svg'),
    }),
  );
}
