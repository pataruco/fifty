// Writes src/generated/assets.ts from the stylesheet. Every runtime (the
// Worker, its tests and plain Node) imports that one module, so they all
// inline the same bytes under the same CSP hash.
//
// Run: node scripts/build-styles.ts
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { transform } from 'esbuild';

export interface AssetSources {
  css: string;
}

const BANNER = '// Generated by scripts/build-styles.ts — do not edit.\n';

export async function buildAssetsModule(
  sources: AssetSources,
): Promise<string> {
  const { code } = await transform(sources.css, {
    loader: 'css',
    minify: true,
  });
  const css = code.trimEnd();
  const styleHash = `sha256-${createHash('sha256').update(css, 'utf8').digest('base64')}`;

  return [
    BANNER,
    `export const css: string = ${JSON.stringify(css)};`,
    '',
    `export const styleHash: \`sha256-\${string}\` = ${JSON.stringify(styleHash)};`,
    '',
  ].join('\n');
}

const source = (path: string) => new URL(path, import.meta.url);

if (import.meta.main) {
  const css = await readFile(source('../src/styles/fifty.css'), 'utf8');
  await writeFile(
    source('../src/generated/assets.ts'),
    await buildAssetsModule({ css }),
  );
}
